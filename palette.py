"""The pair view's colours: espmap v0.2.1's own vik and lajolla tables,
frozen in vendor/espmap_v0_2_1_colormaps.json (generated by
vendor/make_espmap_colormaps.py; never hand-edited).

espmap owns the colour convention: warm = negative on vik, V_min darkest on
lajolla. This module only looks values up, by espmap's own rule, and never
reverses, flips or reinterprets a table. The table is part of the pair
view's contract: a later espmap palette is a deliberate contract change,
never followed automatically, so a page built from the same record and
scale stays visually reproducible. No espmap import: CI tests the colours
without espmap's scientific stack.
"""
import json
import math
from pathlib import Path

TABLES = json.loads((Path(__file__).with_name("vendor") / "espmap_v0_2_1_colormaps.json")
                    .read_text(encoding="utf-8"))


def index(cmap, t):
    """espmap's lookup (matplotlib's on a float): t clipped to [0, 1],
    i = min(int(t * N), N - 1)."""
    if cmap not in TABLES["maps"]:
        raise ValueError(f"no frozen table for colour map {cmap!r}; the pair view has {sorted(TABLES['maps'])}")
    if not (isinstance(t, (int, float)) and not isinstance(t, bool) and math.isfinite(t)):
        raise ValueError(f"{t!r} is not a finite number to colour")
    n = TABLES["maps"][cmap]["N"]
    return min(int(min(max(t, 0.0), 1.0) * n), n - 1)


def rgba(cmap, t):
    return tuple(TABLES["maps"][cmap]["rgba"][index(cmap, t)])


def hex_colours(values, vmin, vmax, cmap):
    """One '#rrggbb' per value on the scale [vmin, vmax], as views.colours
    writes them (int(255 * channel)); values outside the scale take its
    end colours."""
    if not (math.isfinite(vmin) and math.isfinite(vmax) and vmin < vmax):
        raise ValueError(f"[{vmin}, {vmax}] is not a scale to colour on")
    return ["#%02x%02x%02x" % tuple(int(255 * c) for c in rgba(cmap, (float(v) - vmin) / (vmax - vmin))[:3])
            for v in values]
